interface Who {
  owner: boolean;
  open: boolean;
  look: LookState;
}

const platformName = (p: BuilderPlatform): string => builderPlatforms.find((b) => b.id === p)?.label ?? p;

/** The STIG page a builder platform's rules are drawn on: the three mobile platforms share one. */
const stigPlatform = (p: BuilderPlatform): string => (p === "ios" || p === "ipados" || p === "android" ? "mobile" : p);

export function renderBaselinesIndex(options: { db: DatabaseSync } & Who): string {
  const { db, owner, open, look } = options;
  const cards = builderPlatforms.map((p) => {
    const s = builderSummary(db, p.id);
    const stigs = `/stigs/${stigPlatform(p.id)}`;
    return html`<li class="std">
      <div class="std-head"><b><a href="/baselines/${p.id}">${p.label}</a></b>${s.stigs.length ? html`<a class="state ok" href="${stigs}">${s.stigs.length} STIG${s.stigs.length === 1 ? "" : "s"} loaded</a>` : html`<a class="state wait" href="${stigs}">No STIG loaded</a>`}</div>
      <div class="std-meta"><span>${s.stigs.length ? s.stigs.map((st, i) => html`${i ? ", " : ""}<a href="${stigs}?stig=${encodeURIComponent(st.key)}">${st.product}</a>`) : html`<a href="/watchlist">follow a STIG first</a>`}</span>${p.id === "windows" ? html`<a class="n" href="/standards/microsoft-sct">${s.scts} Microsoft baseline${s.scts === 1 ? "" : "s"}</a>` : ""}${usesMscp(p.id) ? html`<a class="n" href="/standards/nist-mscp">${s.mscps} mSCP branch${s.mscps === 1 ? "" : "es"}</a>` : ""}<a class="n" href="/standards/nist-sp-800-53b">${s.high ? "SP 800-53 High loaded" : "SP 800-53 High not loaded"}</a></div>
      <p class="std-note">${p.blurb}</p>
    </li>`;
  });
  const content = html`
    <div class="cols">
      <section class="main">
        <h1>Baselines</h1>
        <p class="lede">The strictest published profile for a platform, built from what the Register holds: every CAT I and CAT II rule of a STIG, the matching Microsoft baseline or NIST macOS rules, and the NIST SP 800-53 High baseline controls. Untick what you cannot do, and export the rest as a guide for Jamf, Intune or a Linux shell. Nothing on these pages is generated by a model; every line is the publisher's.</p>
        <ul class="stds">${cards}</ul>
      </section>
      <aside class="side">
        <section class="box">
          <h2><a href="/guide#register">How a profile is built</a></h2>
          <p class="small">A STIG's rules come first. On Windows, Microsoft's Security Compliance Toolkit settings are joined to rules by registry path and the rest listed as what Microsoft adds; DISA's own Intune policy and checklist say which rules its settings-catalog policy sets and which are outside its scope. On macOS, NIST's macOS Security Compliance Project rules are joined by STIG id and carry the configuration-profile keys. Every rule maps to SP 800-53 through DISA's CCIs; the High baseline's controls close the list, each with the rules that implement it.</p>
        </section>
        <section class="box">
          <h2><a href="/guide#register">What is never exported</a></h2>
          <p class="small">CIS Benchmark text (your own upload, your own licence) and anything a model wrote. Microsoft's values appear only as the page quotes them. Each export carries the publishers' attributions.</p>
        </section>
        <section class="box">
          <h2><a href="/platforms">Test plans</a></h2>
          <p class="small">What to test on a new OS release so the baseline still holds, by area, from the STIG and mSCP checks plus the owner's templates: <a href="/baselines/windows/tests">Windows</a>, <a href="/baselines/macos/tests">macOS</a>, <a href="/baselines/linux/tests">Linux</a>; from the templates alone: <a href="/baselines/ios/tests">iOS</a>, <a href="/baselines/ipados/tests">iPadOS</a>, <a href="/baselines/android/tests">Android</a>, <a href="/baselines/collaboration/tests">Collaboration</a>. Each release and the hardware it runs on are on the <a href="/platforms">Platforms</a> page.</p>
        </section>
      </aside>
    </div>`;
  return page({ title: "Baselines", active: "baselines", content, meta: html`${builderPlatforms.length} platforms`, owner, open, look });
}

function choiceValue(c: DocChoice): string {
  return `${c.key}@${c.documentId}`;
}

function select(name: string, label: string, choices: DocChoice[], chosen: DocChoice | null, none: string): Html {
  if (choices.length === 0) return html`<span class="small">${none}</span>`;
  return html`<label for="${name}">${label}</label>
    <select id="${name}" name="${name}">${choices.map((c) => html`<option value="${choiceValue(c)}" ${chosen && c.documentId === chosen.documentId ? "selected" : ""}>${c.label}${c.publishedAt ? ` (${c.publishedAt.slice(0, 10)})` : ""}</option>`)}</select>`;
}

function severityChip(item: ProfileItem): Html {
  if (!item.severity) return html``;
  const level = item.severity === "CAT I" || item.severity === "high" ? "critical" : item.severity === "CAT II" || item.severity === "medium" ? "high" : "medium";
  return html`<span class="chip sev ${level}">${item.severity}</span>`;
}

/**
 * One item: the checkbox, the label and title, the facts as chips, and the apply lines (and the
 * check and fix text when asked for) folded away. Kept tight: a section draws a few hundred of
 * these and a phone loads them all. A Microsoft setting's title is its registry path and its
 * value is a chip, so it carries no apply lines; a control's implementers are in its chips.
 */
function itemRow(platform: string, item: ProfileItem, flavour: Flavour, base: string | null, text: boolean): Html {
  const apply = item.kind === "control" || item.kind === "sct" ? [] : applyLines(item, flavour).filter((l) => l.label !== "Check" && l.label !== "Fix");
  const meta: Html[] = [decisionChip(platform, item)];
  if (item.kind === "control") meta.push(html`<span class="small">${item.implementedBy.length ? html`implemented by ${item.implementedBy.slice(0, 8).join(", ")}${item.implementedBy.length > 8 ? html` and ${item.implementedBy.length - 8} more` : ""}` : "organisational: no technical rule in this profile"}</span>`);
  else if (item.controls.length) meta.push(html`<span>${item.controls.map((c, i) => html`${i ? ", " : ""}${base ? html`<a href="${base}/${c}">${controlLabel(c)}</a>` : controlLabel(c)}`)}</span>`);
  else if (item.kind === "stig") meta.push(html`<span class="small">no control mapping</span>`);
  if (item.mscp) meta.push(html`<span class="chip">mSCP ${item.mscp.id}</span>`);
  if (item.intune.length) meta.push(html`<span class="chip ins">Intune: ${item.intune.length} definition${item.intune.length === 1 ? "" : "s"}</span>`);
  if (item.checklist) meta.push(html`<span class="chip ${item.checklist.status === "NotAFinding" ? "ins" : item.checklist.status === "Not_Applicable" ? "mod" : ""}">DISA: ${item.checklist.label}</span>`);
  if (item.sctValue !== null) meta.push(html`<span class="chip">Microsoft baseline: ${item.sctValue}</span>`);
  const withText = text && (item.check !== null || item.fix !== null);
  const summary = apply.length && withText ? "How to apply, check and fix" : apply.length ? "How to apply" : item.check && item.fix ? "Check and fix" : item.check ? "Check" : "Fix";
  const folded =
    apply.length || withText
      ? html`<details><summary>${summary}</summary>${apply.length ? html`<dl class="pitem-apply">${apply.map((l) => html`<dt>${l.label}</dt><dd>${l.text.length > 400 ? `${l.text.slice(0, 399)}…` : l.text}</dd>`)}</dl>` : ""}${withText && item.check ? html`<h4 class="small">Check</h4><p class="prose">${lines(item.check)}</p>` : ""}${withText && item.fix ? html`<h4 class="small">Fix</h4><p class="prose">${lines(item.fix)}</p>` : ""}</details>`
      : "";
  return html`<li class="pitem ${item.included ? "" : "off"} ${item.kind}"><label class="pitem-head"><input type="checkbox" name="keep" value="${item.id}" ${item.included ? "checked" : ""}> <a href="${item.url}"><b>${item.label}</b></a> ${severityChip(item)} <span class="pitem-title">${item.title}</span></label>${meta.length ? html`<div class="pitem-meta">${meta.map((m, i) => (i ? html` ${m}` : m))}</div>` : ""}${folded}</li>
`;
}

function nextBox(n: NextComparison): Html {
  const what = n.component === "stig" ? "STIG" : n.component === "sct" ? "Microsoft baseline" : "mSCP";
  const list = (rows: { label: string; title: string; what?: string }[], chip: string, kind: string) =>
    rows.length ? html`<ul class="change-list">${rows.slice(0, 10).map((r) => html`<li><b>${r.label}</b> <span class="chip ${kind}">${chip}</span> ${r.title}${r.what ? html` <span class="small">(${r.what})</span>` : ""}</li>`)}${rows.length > 10 ? html`<li class="small">and ${rows.length - 10} more</li>` : ""}</ul>` : "";
  return html`<section class="box">
    <h2><a href="/standards/${n.next.source}/${n.next.documentId}">${what}: current versus next</a></h2>
    <p class="small">${n.current.label} against <a href="/standards/${n.next.source}/${n.next.documentId}">${n.next.label}</a>${n.next.publishedAt ? ` (${n.next.publishedAt.slice(0, 10)})` : ""}: the strict set gains ${n.added.length}, loses ${n.removed.length}, and ${n.changed.length} change${n.changed.length === 1 ? "s" : ""}.</p>
    ${list(n.added, "gains", "ins")}${list(n.removed, "loses", "del")}${list(n.changed, "changes", "mod")}
  </section>`;
}

export interface BuilderOptions extends Who {
  db: DatabaseSync;
  profile: Profile;
  flavour: Flavour;
  /** The section to draw; the first with items when absent or empty. */
  section?: SectionId | undefined;
  /** Whether to fold each rule's check and fix text into its row (a megabyte on a big STIG). */
  text?: boolean;
}

/** What a section is, under its heading. */
function sectionBlurb(section: ProfileSection, profile: Profile): string {
  const c = profile.components;
  switch (section.id) {
    case "cat1":
      return `Every CAT I rule of ${c.stig?.label ?? "the STIG"}: the ones DISA rates most severe.`;
    case "cat2":
      return `Every CAT II rule of ${c.stig?.label ?? "the STIG"}.`;
    case "cat3":
      return `The CAT III rules of ${c.stig?.label ?? "the STIG"}, included because you asked for them.`;
    case "sct":
      return `Settings in ${c.sct?.label ?? "the Microsoft baseline"} that no rule of the STIG names by registry path. Values are Microsoft's, quoted from this instance's copy.`;
    case "mscp":
      return `Rules in ${c.mscp?.label ?? "mSCP"}'s SP 800-53 High or DISA STIG baseline that join no rule of the chosen STIG.`;
    case "controls":
      return `Every control in the High baseline, each with the kept rules that implement it through DISA's CCIs${usesMscp(profile.platform) ? " and mSCP's references" : ""}. A control with none is organisational: policy, process or something no technical rule reaches.`;
  }
}

export function renderBuilder(options: BuilderOptions): string {
  const { db, profile, flavour, owner, open, look, text = false } = options;
  const p = profile.platform;
  const name = platformName(p);
  const base = controlPageBase(db);
  const c = profile.components;
  const sections = profileSections(profile);
  const current = sections.find((s) => s.id === options.section) ?? sections[0];
  // The other sections' drops ride along as hidden fields; the current section's are its unticked boxes.
  const carried = current ? profile.items.filter((i) => !i.included && sectionOf(i) !== current.id) : [];
  const groups: { section: string; items: ProfileItem[] }[] = [];
  for (const item of current?.items ?? []) {
    const last = groups[groups.length - 1];
    if (last && last.section === item.section) last.items.push(item);
    else groups.push({ section: item.section, items: [item] });
  }
  const list = (items: ProfileItem[]): Html => html`<ol class="pitems">${items.map((i) => itemRow(p, i, flavour, base, text))}</ol>`;
  const group = (g: { section: string; items: ProfileItem[] }): Html => html`<details class="box pgroup">
    <summary><b>${g.section}</b> <span class="count">${g.items.filter((i) => i.included).length} of ${g.items.length} kept</span></summary>
    ${list(g.items)}
  </details>`;
  const platformFlavours = flavours.filter((f) => f.id === "plain" || (usesMscp(p) && f.id === "jamf") || (p === "windows" && f.id === "intune") || (p === "linux" && f.id === "linux"));
  // A section's heading as a plain link: the documents it was built from ride along, the unticked items start from the owner's decisions.
  const sectionHref = (id?: SectionId): string => {
    const q = new URLSearchParams();
    if (c.stig) q.set("stig", choiceValue(c.stig));
    if (c.sct) q.set("sct", choiceValue(c.sct));
    if (c.mscp) q.set("mscp", choiceValue(c.mscp));
    if (profile.options.cat3) q.set("cat3", "1");
    if (id) q.set("section", id);
    const s = q.toString();
    return `/baselines/${p}${s ? `?${s}` : ""}`;
  };

  const main = !c.stig
    ? html`<div class="empty"><b>No ${name} STIG loaded.</b><p>${owner ? html`Follow one through the <a href="/watchlist">watchlist</a> and fetch the DISA library from <a href="/sources">Sources</a>.` : "The owner can follow one through the watchlist."}</p></div>`
    : html`<form method="post" action="/baselines/${p}" class="builder">
        <input type="hidden" name="applied" value="1">
        ${current ? html`<input type="hidden" name="shown" value="${current.id}">` : ""}
        ${carried.map((i) => html`<input type="hidden" name="drop" value="${i.id}">`)}
        <fieldset class="build-from">
          <legend>Build from</legend>
          ${select("stig", "STIG", profile.choices.stigs, c.stig, "No STIG loaded")}
          ${p === "windows" ? select("sct", "Microsoft baseline", profile.choices.scts, c.sct, "No Microsoft baseline loaded (fetch the Security Compliance Toolkit from Sources)") : ""}
          ${usesMscp(p) ? select("mscp", "mSCP branch", profile.choices.mscps, c.mscp, "No mSCP branch loaded (fetch the macOS Security Compliance Project from Sources)") : ""}
          <label class="inline-check"><input type="checkbox" name="cat3" value="1" ${profile.options.cat3 ? "checked" : ""}> Include CAT III</label>
          <label class="inline-check"><input type="checkbox" name="text" value="1" ${text ? "checked" : ""}> Show check and fix text</label>
          <button type="submit" name="action" value="rebuild">Rebuild</button>
        </fieldset>
        <fieldset class="export-row">
          <legend>Export the kept items</legend>
          <label for="flavour">Apply with</label>
          <select id="flavour" name="flavour">${platformFlavours.map((f) => html`<option value="${f.id}" ${f.id === flavour ? "selected" : ""}>${f.label}</option>`)}</select>
          <button type="submit" formaction="/baselines/${p}/export" name="format" value="html">Printable HTML</button>
          <button type="submit" formaction="/baselines/${p}/export" name="format" value="md">Markdown</button>
          <button type="submit" formaction="/baselines/${p}/export" name="format" value="csv">CSV</button>
          <button type="submit" formaction="/baselines/${p}/export" name="format" value="json">JSON</button>
          <span class="small">${platformFlavours.find((f) => f.id === flavour)?.blurb ?? ""} Untick an item, then Rebuild or export; the page starts from the owner's decisions, so an item marked not applying starts unticked. One section is drawn at a time; what you untick in one is kept when you open another, and every export covers the whole profile.</span>
        </fieldset>
        ${owner
          ? html`<fieldset class="export-row">
          <legend>Record the unticked items as not applying</legend>
          <label for="bulk-reason">Reason</label> <input id="bulk-reason" name="reason" maxlength="2000" placeholder="Why the organisation does not apply them">
          <label for="bulk-owner">Owner</label> <input id="bulk-owner" name="owner" maxlength="120">
          <button type="submit" formaction="/baselines/${p}/decide-unticked">Save as not applying</button>
          <span class="small">Every unticked item in every section becomes a decision, so the next visit, the exports and the test plan all start from it. Change one later from its chip.</span>
        </fieldset>`
          : ""}
        <nav class="ptabs" aria-label="Sections of the profile">${sections.map((s) => html`<button type="submit" name="section" value="${s.id}" class="${s.id === current?.id ? "on" : ""}" ${s.id === current?.id ? html`aria-current="true"` : ""}>${s.label} <span class="count">${s.kept} of ${s.items.length}</span></button>`)}</nav>
        ${current ? html`<h2><a href="${sectionHref(current.id)}">${current.label}</a> <span class="count"><a href="${sectionHref(current.id)}">${current.kept} kept</a></span></h2><p class="small">${sectionBlurb(current, profile)}</p>${groups.length === 1 ? list(groups[0]!.items) : groups.map(group)}` : html`<p class="small">The STIG has no CAT I or CAT II rules to draw.</p>`}
        ${sections.some((s) => s.id === "controls") ? "" : html`<p class="small">The SP 800-53 High baseline is not loaded; fetch NIST SP 800-53B from Sources to close the list with its controls.</p>`}
      </form>`;

  const aside = html`
    <section class="box">
      <h2><a href="/register">Built from</a></h2>
      <dl class="kv">
        ${c.stig ? html`<dt>STIG</dt><dd><a href="/standards/disa-stigs/${c.stig.documentId}">${c.stig.label}</a>${c.stig.publishedAt ? html` <span class="small">${c.stig.publishedAt.slice(0, 10)}</span>` : ""}</dd>` : ""}
        ${c.sct ? html`<dt>Microsoft baseline</dt><dd><a href="/standards/microsoft-sct/${c.sct.documentId}">${c.sct.label}</a></dd>` : p === "windows" ? html`<dt>Microsoft baseline</dt><dd>not loaded</dd>` : ""}
        ${c.mscp ? html`<dt>mSCP</dt><dd><a href="/standards/nist-mscp/${c.mscp.documentId}">${c.mscp.label}</a></dd>` : usesMscp(p) ? html`<dt>mSCP</dt><dd>not loaded</dd>` : ""}
        <dt>Controls</dt><dd>${c.controls ? html`<a href="/standards/nist-sp-800-53b/${c.controls.documentId}">${c.controls.label}</a>` : "High baseline not loaded"}${c.cciVersion ? html`<br><span class="small">CCI list ${c.cciVersion}</span>` : html`<br><span class="small">CCI list not loaded: no rule-to-control mapping</span>`}</dd>
        ${p === "windows" ? html`<dt>DISA Intune policy</dt><dd>${c.intune ? html`<a href="/standards/disa-intune/${c.intune.documentId}">${c.intune.label}</a> <span class="small">${c.intune.version ?? ""}</span>` : "none for this STIG in DISA's package"}</dd><dt>DISA checklist</dt><dd>${c.checklist ? html`<a href="/standards/disa-gpo/${c.checklist.documentId}">${c.checklist.label}</a> <span class="small">${c.checklist.version ?? ""}</span>` : "none for this STIG in DISA's package"}</dd>` : ""}
        <dt>Kept</dt><dd><a href="${sectionHref(current?.id)}">${profile.counts.included} of ${profile.items.length}${profile.counts.dropped ? ` (${profile.counts.dropped} dropped)` : ""}</a></dd>
        <dt>Decisions</dt><dd><a href="/baselines/${p}/decisions">${profile.counts.decisions.modify} modified, ${profile.counts.decisions.exclude} not applied</a>; the rest as published</dd>
      </dl>
    </section>
    ${profile.next.map(nextBox)}
    ${c.stig && profile.next.length === 0 ? html`<section class="box"><h2><a href="/standards/disa-stigs">Current versus next</a></h2><p class="small">No newer version of the STIG${p === "windows" ? ", the Microsoft baseline" : usesMscp(p) ? " or the next mSCP branch" : ""} is loaded; when one arrives this box lists what the strict set gains and loses.</p></section>` : ""}
    <section class="box">
      <h2><a href="/guide#register">Whose words</a></h2>
      <p class="small">STIG rules: DISA (public domain). Controls: NIST SP 800-53 Rev 5 (public domain), mapped through DISA's CCIs. ${usesMscp(p) ? "Apple rules and payload keys: NIST's macOS Security Compliance Project. " : ""}${p === "windows" ? "Microsoft's values: your own copy of the Security Compliance Toolkit, never redistributed. Intune definitions and checklist verdicts: DISA's own packages. " : ""}No CIS text, nothing from a model.</p>
      <p class="small"><a href="/baselines/${p}/decisions">The ${name} decisions</a> · <a href="/baselines/${p}/tests">The ${name} test plan</a> · <a href="/stigs/${stigPlatform(p)}">The ${name} STIG pages</a> · <a href="/baselines">All platforms</a></p>
    </section>`;

  const content = html`
    <div class="rel">
      <h1>${name} <span class="arrow">strictest published profile</span></h1>
      <div class="when">${c.stig ? html`${c.stig.label}${c.sct ? html` + ${c.sct.label}` : ""}${c.mscp ? html` + ${c.mscp.label}` : ""}${c.controls ? " + SP 800-53 High" : ""}` : "nothing to build from yet"}</div>
    </div>
    <div class="cols">
      <section class="main">${main}</section>
      <aside class="side">${aside}</aside>
    </div>`;
  return page({ title: `${name} baseline`, active: "baselines", content, meta: html`${profile.counts.included} items`, owner, open, look });
}

